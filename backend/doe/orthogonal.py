def list_oa_names() -> list[str]:
    return list(_OA_TABLES.keys())


def get_oa_info(name: str) -> dict:
    return _OA_TABLES.get(name, {})


def apply_orthogonal_array(
    oa_name: str,
    factors: list[Factor],
) -> tuple[pd.DataFrame, str]:
    """
    直交表を因子の水準にマッピングして設計点を返す。

    Returns:
        (design_df, warning_msg)
        - warning_msg が空でない場合、因子数が直交表の列数を超えている等
    """
    info = _OA_TABLES.get(oa_name)
    if info is None:
        return pd.DataFrame(), f"直交表 '{oa_name}' は見つかりません"

    oa_array = info["array"]
    max_factors = info["n_factors_max"]
    n_factors = len(factors)
    warning = ""

    if n_factors > max_factors:
        warning = (
            f"⚠️ {oa_name} は最大 {max_factors} 因子まで対応していますが、"
            f"{n_factors} 因子が指定されています。最初の {max_factors} 因子のみ使用します。"
        )
        factors = factors[:max_factors]
        n_factors = max_factors

    # 各因子の水準数チェック
    col_levels = info.get("col_levels")
    rows = {}
    for fi, factor in enumerate(factors):
        col_idx = fi
        if col_levels is not None:
            oa_n_levels = col_levels[col_idx]
        else:
            oa_n_levels = info["n_levels"]

        lvls = factor.levels
        if len(lvls) < oa_n_levels:
            # 水準が足りない場合: 循環的に補完
            extended = (lvls * (oa_n_levels // len(lvls) + 1))[:oa_n_levels]
        else:
            extended = lvls[:oa_n_levels]

        col_data = oa_array[:, col_idx]
        rows[factor.name] = [extended[int(v) % len(extended)] for v in col_data]

    df = pd.DataFrame(rows)
    return df, warning
